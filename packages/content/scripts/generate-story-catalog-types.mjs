import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const catalogPath = resolve(packageRoot, "catalog/story-catalog.json");
const outputPath = resolve(packageRoot, "src/story-catalog.generated.ts");

const args = new Set(process.argv.slice(2));
const supportedArgs = new Set(["--check"]);
for (const arg of args) {
  if (!supportedArgs.has(arg)) {
    throw new Error(`Unknown argument: ${arg}`);
  }
}

function requireRecord(value, path) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${path} must be an object`);
  }
  return value;
}

function requireArray(value, path) {
  if (!Array.isArray(value)) {
    throw new Error(`${path} must be an array`);
  }
  return value;
}

function requireString(value, path) {
  if (typeof value !== "string" || value.trim().length === 0) {
    throw new Error(`${path} must be a non-empty string`);
  }
  return value;
}

function requireUnique(values, path) {
  const seen = new Set();
  for (const value of values) {
    if (seen.has(value)) {
      throw new Error(`${path} contains duplicate value ${JSON.stringify(value)}`);
    }
    seen.add(value);
  }
}

function formatStringArray(name, values) {
  const singleLine = `export const ${name} = [${values.map((value) => JSON.stringify(value)).join(", ")}] as const;`;
  if (singleLine.length <= 100) {
    return singleLine;
  }
  const rows = values.map((value) => `  ${JSON.stringify(value)},`).join("\n");
  return `export const ${name} = [\n${rows}\n] as const;`;
}

const catalog = requireRecord(JSON.parse(readFileSync(catalogPath, "utf8")), "story catalog");
const productionChapters = requireArray(
  catalog.productionChapters,
  "story catalog productionChapters",
).map((entry, index) => requireRecord(entry, `story catalog productionChapters[${index}]`));
const devChapters = requireArray(catalog.devChapters, "story catalog devChapters").map(
  (entry, index) => requireRecord(entry, `story catalog devChapters[${index}]`),
);
const packages = requireArray(catalog.packages, "story catalog packages").map((entry, index) =>
  requireRecord(entry, `story catalog packages[${index}]`),
);

const productionIds = productionChapters.map((entry, index) =>
  requireString(entry.id, `story catalog productionChapters[${index}].id`),
);
const devIds = devChapters.map((entry, index) =>
  requireString(entry.id, `story catalog devChapters[${index}].id`),
);
const storyIds = [...productionIds, ...devIds];
const packageIds = packages.map((entry, index) =>
  requireString(entry.packageId, `story catalog packages[${index}].packageId`),
);
requireUnique(storyIds, "story catalog chapter ids");
requireUnique(packageIds, "story catalog package ids");

const defaultPackageId = requireString(catalog.defaultPackageId, "story catalog defaultPackageId");
const defaultPackageIndex = packageIds.indexOf(defaultPackageId);
if (defaultPackageIndex < 0) {
  throw new Error(`story catalog defaultPackageId ${JSON.stringify(defaultPackageId)} is unknown`);
}
const defaultPackage = packages[defaultPackageIndex];
if (!defaultPackage) {
  throw new Error("story catalog has no default package");
}
const defaultStoryId = requireString(
  defaultPackage.startChapterId,
  `story catalog packages[${defaultPackageIndex}].startChapterId`,
);
if (!storyIds.includes(defaultStoryId)) {
  throw new Error(
    `story catalog default startChapterId ${JSON.stringify(defaultStoryId)} is not a registered chapter`,
  );
}
const defaultChapterIds = requireArray(
  defaultPackage.chapterIds,
  `story catalog packages[${defaultPackageIndex}].chapterIds`,
).map((value, index) =>
  requireString(value, `story catalog packages[${defaultPackageIndex}].chapterIds[${index}]`),
);
if (!defaultChapterIds.includes(defaultStoryId)) {
  throw new Error("story catalog default package chapterIds must include its startChapterId");
}
for (const chapterId of defaultChapterIds) {
  if (!storyIds.includes(chapterId)) {
    throw new Error(
      `story catalog default package references unknown chapter ${JSON.stringify(chapterId)}`,
    );
  }
}

const generated = `// This file is generated by scripts/generate-story-catalog-types.mjs.
// Do not edit it by hand; edit catalog/story-catalog.json and regenerate instead.

${formatStringArray("PRODUCTION_STORY_CATALOG_IDS", productionIds)}

export type ProductionStoryCatalogId = (typeof PRODUCTION_STORY_CATALOG_IDS)[number];

${formatStringArray("DEV_STORY_CATALOG_IDS", devIds)}

export type DevStoryCatalogId = (typeof DEV_STORY_CATALOG_IDS)[number];

${formatStringArray("STORY_CATALOG_IDS", storyIds)}

export type StoryCatalogId = (typeof STORY_CATALOG_IDS)[number];

${formatStringArray("STORY_PACKAGE_IDS", packageIds)}

export type StoryPackageId = (typeof STORY_PACKAGE_IDS)[number];

export const DEFAULT_STORY_PACKAGE_ID = ${JSON.stringify(defaultPackageId)} as const satisfies StoryPackageId;

export const DEFAULT_STORY_ID = ${JSON.stringify(defaultStoryId)} as const satisfies StoryCatalogId;
`;

if (args.has("--check")) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : null;
  if (current !== generated) {
    console.error(
      "story-catalog.generated.ts is stale; run pnpm --filter @supaluv/content generate-story-catalog-types",
    );
    process.exitCode = 1;
  } else {
    console.log("story catalog generated types are current");
  }
} else {
  writeFileSync(outputPath, generated, "utf8");
  console.log("generated src/story-catalog.generated.ts");
}
